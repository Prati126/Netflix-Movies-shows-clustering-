""" Selecting the Number of Clusters Using the Elbow Method

The Elbow Method helps explore a suitable number of clusters for K-Means.

It compares the within-cluster sum of squares for different values of K. As the number of clusters increases, this value generally decreases.

An elbow-shaped bend may indicate a useful trade-off between cluster compactness and model complexity. In this project, the graph does not show a very clear elbow, so selecting five clusters is an exploratory choice rather than a definitive optimum.
"""

from scipy.cluster.hierarchy import dendrogram, linkage
import matplotlib.pyplot as plt
dendrogram_data = sample_matrix[:200]
linked = linkage(dendrogram_data, method='ward')
plt.figure(figsize=(12, 6))
dendrogram( linked,truncate_mode='lastp',p=30,leaf_rotation=90,leaf_font_size=8)
plt.title('Dendrogram for Netflix Content Clustering')
plt.xlabel('Content Groups')
plt.ylabel('Distance')
plt.tight_layout()
plt.show()

"""Hierarchical Clustering Visualization Using a Dendrogram

A dendrogram visualizes the hierarchical merging process in Agglomerative Clustering.

In this project, the dendrogram is generated using a subset of 200 records from the sampled feature matrix. The tree structure illustrates how groups of observations merge at different distances.

The dendrogram helps explore the hierarchy of the sample, but it does not by itself establish the best number of clusters for the full dataset.

Evaluating Clustering Performance Using the Silhouette Score

The Silhouette Score measures how well observations fit within their assigned clusters compared with other clusters.

For the 1,000-record sample, the K-Means Silhouette Score is approximately 0.0479, while the Agglomerative Clustering score is approximately 0.0142.

Both scores are close to zero, indicating weak separation between clusters. K-Means performs slightly better than Agglomerative Clustering under this particular sample and evaluation setup.

These results suggest that the current clustering configurations do not produce strongly separated groups. Further experimentation with feature engineering and clustering parameters may improve the results.
"""

from sklearn.metrics import silhouette_score
